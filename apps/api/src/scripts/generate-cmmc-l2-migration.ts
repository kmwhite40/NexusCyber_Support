// Generates the SQL migration that loads the CMMC Level 2 practice catalog into compliance_controls.
//
// CMMC Level 2 is the 110 security requirements of NIST SP 800-171 Rev. 2 (32 CFR 170.14(c)(3)).
// The requirement text and discussion come from NIST's official Rev. 2 dataset in the Cybersecurity
// and Privacy Reference Tool (a U.S. Government work, public domain):
//   https://csrc.nist.gov/extensions/nudp/services/json/nudp/framework/version/sp_800_171_2_0_0/export/json?element=all
// NIST does not publish CMMC levels. The 17 Level 1 practices are the FAR 52.204-21 set fixed by
// 32 CFR 170.14(c)(2), listed below; every other requirement is a Level 2 practice.
//
// Practice ids are the CMMC form "<family>.L<level>-<requirement>", e.g. "AC.L1-3.1.1",
// "AC.L2-3.1.5", the form CMMC assessment guides, SSPs and this repo's risk registers cite.
//
// Usage (from apps/api):
//   npx tsx src/scripts/generate-cmmc-l2-migration.ts <cprt-800-171r2.json> > src/db/migrations/NNNN_cmmc_l2_catalog.sql
//
// Output is deterministic for a given dataset: practices in requirement order.
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

interface Element { element_type: string; element_identifier: string; title?: string; text?: string }

const path = process.argv[2];
if (!path) { console.error('usage: generate-cmmc-l2-migration.ts <cprt-800-171r2.json>'); process.exit(1); }
const raw = readFileSync(path, 'utf8');
const data = JSON.parse(raw).response.elements as { documents: Array<{ doc_identifier: string; version: string }>; elements: Element[] };
if (data.documents[0]?.doc_identifier !== 'SP_800_171_2_0_0') throw new Error(`expected SP 800-171 Rev. 2, got ${data.documents[0]?.doc_identifier}`);

// 800-171 family number -> CMMC domain abbreviation (CMMC Model v2, 32 CFR 170.14(c)(1)).
const DOMAIN: Record<string, string> = {
  '3.1': 'AC', '3.2': 'AT', '3.3': 'AU', '3.4': 'CM', '3.5': 'IA', '3.6': 'IR', '3.7': 'MA',
  '3.8': 'MP', '3.9': 'PS', '3.10': 'PE', '3.11': 'RA', '3.12': 'CA', '3.13': 'SC', '3.14': 'SI',
};
// The 15 FAR 52.204-21(b)(1) requirements as the 17 CMMC Level 1 practices, 32 CFR 170.14(c)(2).
const LEVEL1 = new Set([
  '3.1.1', '3.1.2', '3.1.20', '3.1.22', '3.5.1', '3.5.2', '3.8.3', '3.10.1', '3.10.3', '3.10.4',
  '3.10.5', '3.13.1', '3.13.5', '3.14.1', '3.14.2', '3.14.4', '3.14.5',
]);

const titleCase = (s: string) => s.toLowerCase().replace(/\b([a-z])/g, (c) => c.toUpperCase()).replace(/\bAnd\b/g, 'and');
const families = new Map(data.elements.filter((e) => e.element_type === 'family').map((e) => [e.element_identifier, titleCase(e.title ?? '')]));
const discussion = new Map(data.elements.filter((e) => e.element_type === 'discussion').map((e) => [e.element_identifier.replace(/^D_/, ''), (e.text ?? '').trim()]));
const reqs = data.elements.filter((e) => e.element_type === 'requirement');

const num = (id: string) => id.split('.').map(Number);
reqs.sort((a, b) => { const x = num(a.element_identifier), y = num(b.element_identifier); return x[1] - y[1] || x[2] - y[2]; });

interface Row { id: string; family: string; title: string; description: string }
const rows: Row[] = reqs.map((r) => {
  const req = r.element_identifier;
  const fam = req.split('.').slice(0, 2).join('.');
  const domain = DOMAIN[fam];
  const family = families.get(fam);
  if (!domain || !family) throw new Error(`requirement ${req} has an unknown family ${fam}`);
  const text = (r.text ?? '').replace(/\s+/g, ' ').trim();
  if (!text) throw new Error(`requirement ${req} has no text`);
  const disc = discussion.get(req);
  return {
    id: `${domain}.L${LEVEL1.has(req) ? 1 : 2}-${req}`,
    family,
    // The requirement is one sentence and is what a practice is cited by; the discussion explains it.
    title: text,
    description: disc ? `${text}\n\nDiscussion (NIST SP 800-171 Rev. 2): ${disc}` : text,
  };
});

if (rows.length !== 110) throw new Error(`expected 110 requirements, got ${rows.length}`);
const l1 = rows.filter((r) => r.id.includes('.L1-')).length;
if (l1 !== LEVEL1.size) throw new Error(`expected ${LEVEL1.size} Level 1 practices, matched ${l1}`);
const ids = new Set<string>();
for (const r of rows) {
  if (!/^[A-Z]{2}\.L[12]-3\.\d{1,2}\.\d{1,2}$/.test(r.id)) throw new Error(`unexpected practice id ${r.id}`);
  if (ids.has(r.id)) throw new Error(`duplicate practice id ${r.id}`);
  ids.add(r.id);
}

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const sha = createHash('sha256').update(raw).digest('hex');
const out: string[] = [
  `-- CMMC Level 2 practice catalog: ${rows.length} practices (${l1} Level 1, ${rows.length - l1} Level 2) across ${new Set(rows.map((r) => r.family)).size} domains,`,
  '-- the security requirements of NIST SP 800-171 Rev. 2 (32 CFR 170.14(c)(3)).',
  '--',
  '-- GENERATED by src/scripts/generate-cmmc-l2-migration.ts from NIST\'s official SP 800-171 Rev. 2 dataset',
  `-- (CSRC Cybersecurity and Privacy Reference Tool, SP_800_171_2_0_0, sha256 ${sha}).`,
  '-- Levels follow 32 CFR 170.14(c)(2). NIST SP 800-171 is a work of the U.S. Government and is not subject to copyright.',
  '-- Do not edit by hand; regenerate in a NEW migration.',
  '--',
  '-- Ids are the CMMC form ("AC.L2-3.1.5"), framework \'CMMC-L2\'. Idempotent and non-destructive: rows are',
  '-- upserted by control_id and only CMMC-L2 rows are ever updated. Nothing is deleted.',
  '',
  'INSERT INTO compliance_controls (control_id, framework, family, title, description) VALUES',
  rows.map((r) => `  (${q(r.id)}, 'CMMC-L2', ${q(r.family)}, ${q(r.title)}, ${q(r.description)})`).join(',\n'),
  `ON CONFLICT (control_id) DO UPDATE
  SET family = EXCLUDED.family, title = EXCLUDED.title, description = EXCLUDED.description
  WHERE compliance_controls.framework = 'CMMC-L2';`,
  '',
];
process.stdout.write(out.join('\n'));
console.error(`generated ${rows.length} practices (${l1} Level 1)`);
