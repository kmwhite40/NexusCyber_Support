// Generates the SQL migration that loads the NIST SP 800-53 Rev. 5 control catalog into
// compliance_controls, from NIST's official OSCAL catalog (a U.S. Government work, public domain):
//   https://github.com/usnistgov/oscal-content/blob/main/nist.gov/SP800-53/rev5/json/NIST_SP-800-53_rev5_catalog.json
//
// Usage (from apps/api):
//   npx tsx src/scripts/generate-nist-80053-migration.ts <catalog.json> > src/db/migrations/NNNN_nist_800_53_rev5_catalog.sql
//
// Output is deterministic for a given catalog: controls in catalog order, withdrawn controls
// omitted, ids in the form the rest of Anchor uses ("AC-2", "AC-2(1)").
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

interface Prop { name: string; value: string }
interface Param { id: string; label?: string; select?: { 'how-many'?: string; choice?: string[] }; props?: Prop[] }
interface Part { id?: string; name: string; prose?: string; props?: Prop[]; parts?: Part[] }
interface Control { id: string; title: string; props?: Prop[]; params?: Param[]; parts?: Part[]; controls?: Control[] }
interface Group { id: string; title: string; controls?: Control[] }

const path = process.argv[2];
if (!path) { console.error('usage: generate-nist-80053-migration.ts <catalog.json>'); process.exit(1); }
const raw = readFileSync(path, 'utf8');
const catalog = JSON.parse(raw).catalog as { metadata: { title: string; version: string; 'last-modified': string }; groups: Group[] };

const prop = (x: { props?: Prop[] }, name: string) => x.props?.find((p) => p.name === name)?.value;
const withdrawn = (c: Control) => prop(c, 'status') === 'withdrawn';

/** Render "{{ insert: param, ac-02_odp.01 }}" the way the printed standard does. */
function renderProse(text: string, params: Map<string, Param>, depth = 0): string {
  return text.replace(/\{\{\s*insert:\s*param,\s*([^}\s]+)\s*\}\}/g, (_m, id: string) => {
    const p = params.get(id);
    if (!p || depth > 4) return '[Assignment: organization-defined value]';
    if (p.select?.choice?.length) {
      const how = p.select['how-many'] === 'one-or-more' ? 'Selection (one or more)' : 'Selection';
      return `[${how}: ${p.select.choice.map((ch) => renderProse(ch, params, depth + 1)).join('; ')}]`;
    }
    const label = renderProse(p.label ?? 'value', params, depth + 1);
    // Some ODP labels already read "organization-defined …"; never print it twice.
    return `[Assignment: ${/^organization-defined\b/i.test(label) ? label : `organization-defined ${label}`}]`;
  });
}

function renderStatement(part: Part | undefined, params: Map<string, Param>, indent = ''): string {
  if (!part) return '';
  const label = prop(part, 'label');
  const lines: string[] = [];
  if (part.prose) lines.push(`${indent}${label ? `${label} ` : ''}${renderProse(part.prose, params)}`);
  for (const child of part.parts ?? []) {
    if (child.name !== 'item') continue;
    lines.push(renderStatement(child, params, part.prose ? `${indent}  ` : indent));
  }
  return lines.filter(Boolean).join('\n');
}

interface Row { id: string; family: string; title: string; description: string }
const rows: Row[] = [];
function walk(c: Control, family: string, params: Map<string, Param>, parentTitle?: string) {
  const own = new Map(params);
  for (const p of c.params ?? []) own.set(p.id, p);
  if (!withdrawn(c)) {
    const label = prop(c, 'label');
    if (!label) throw new Error(`control ${c.id} has no label`);
    const statement = (c.parts ?? []).find((p) => p.name === 'statement');
    rows.push({
      // 5.2.0 labels are zero-padded ("AC-02(01)"); Anchor, its imports and every 800-53 citation in
      // the wild use "AC-2(1)".
      id: label.replace(/\s+/g, '').replace(/-0+(\d)/, '-$1').replace(/\(0+(\d)/, '($1'),
      family,
      title: parentTitle ? `${parentTitle} | ${c.title}` : c.title,
      description: renderStatement(statement, own).trim(),
    });
  }
  for (const e of c.controls ?? []) walk(e, family, own, parentTitle ?? c.title);
}
for (const g of catalog.groups) for (const c of g.controls ?? []) walk(c, g.title, new Map());

const ids = new Set<string>();
for (const r of rows) {
  if (!/^[A-Z]{2}-\d{1,2}(\(\d{1,2}\))?$/.test(r.id)) throw new Error(`unexpected control id ${r.id}`);
  if (ids.has(r.id)) throw new Error(`duplicate control id ${r.id}`);
  ids.add(r.id);
}

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const sha = createHash('sha256').update(raw).digest('hex');
const out: string[] = [
  `-- NIST SP 800-53 Rev. 5 control catalog (${catalog.metadata.version}): ${rows.length} active controls and enhancements`,
  `-- across ${catalog.groups.length} families; withdrawn controls omitted.`,
  '--',
  '-- GENERATED by src/scripts/generate-nist-80053-migration.ts from NIST\'s official OSCAL catalog',
  `-- (usnistgov/oscal-content, NIST_SP-800-53_rev5_catalog.json, last-modified ${catalog.metadata['last-modified']},`,
  `-- sha256 ${sha}). NIST SP 800-53 is a work of the U.S. Government and is not subject to copyright.`,
  '-- Do not edit by hand; regenerate from a newer catalog in a NEW migration.',
  '--',
  '-- Idempotent and non-destructive: rows are upserted by control_id; existing NIST-800-53 rows (the',
  '-- 10-control starter set) take the official family/title/statement. Nothing is deleted, so',
  '-- control_mappings and risk_links that reference a control keep working.',
  '',
];
for (let i = 0; i < rows.length; i += 200) {
  const chunk = rows.slice(i, i + 200);
  out.push('INSERT INTO compliance_controls (control_id, framework, family, title, description) VALUES');
  out.push(chunk.map((r) => `  (${q(r.id)}, 'NIST-800-53', ${q(r.family)}, ${q(r.title)}, ${r.description ? q(r.description) : 'NULL'})`).join(',\n'));
  out.push(`ON CONFLICT (control_id) DO UPDATE
  SET family = EXCLUDED.family, title = EXCLUDED.title, description = EXCLUDED.description
  WHERE compliance_controls.framework = 'NIST-800-53';`);
  out.push('');
}
process.stdout.write(out.join('\n'));
console.error(`generated ${rows.length} controls (${catalog.metadata.version}), ${catalog.groups.length} families`);
